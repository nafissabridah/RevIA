-- RevIA - traçabilité par projet : exigence (user story) → critère d'acceptation → code → test → verdict QA.
-- Un projet appartient à un seul utilisateur ; la suppression du compte supprime ses projets (cascade).
CREATE TABLE projet (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proprietaire_id  BIGINT        NOT NULL,
    nom              VARCHAR(120)  NOT NULL,
    description      VARCHAR(2000),
    cree_le          TIMESTAMP     NOT NULL,
    CONSTRAINT fk_projet_proprietaire FOREIGN KEY (proprietaire_id) REFERENCES utilisateur (id) ON DELETE CASCADE
);
CREATE INDEX ix_projet_proprietaire ON projet (proprietaire_id);

CREATE TABLE exigence (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projet_id   BIGINT        NOT NULL,
    reference   VARCHAR(40)   NOT NULL,
    titre       VARCHAR(200)  NOT NULL,
    texte       TEXT          NOT NULL,
    cree_le     TIMESTAMP     NOT NULL,
    CONSTRAINT fk_exigence_projet FOREIGN KEY (projet_id) REFERENCES projet (id) ON DELETE CASCADE
);
CREATE INDEX ix_exigence_projet ON exigence (projet_id);

-- statut : couvert | partiel | non_couvert | non_verifie ; verdict_qa : a_tester | valide | rejete
CREATE TABLE critere (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exigence_id     BIGINT        NOT NULL,
    reference       VARCHAR(20)   NOT NULL,
    texte           TEXT          NOT NULL,
    statut          VARCHAR(20)   NOT NULL,
    preuve          TEXT,
    test            TEXT,
    verdict_qa      VARCHAR(20),
    commentaire_qa  VARCHAR(2000),
    modifie_le      TIMESTAMP     NOT NULL,
    CONSTRAINT fk_critere_exigence FOREIGN KEY (exigence_id) REFERENCES exigence (id) ON DELETE CASCADE
);
CREATE INDEX ix_critere_exigence ON critere (exigence_id);
