-- RevIA - jetons d'API personnels (intégration CI : GitHub Actions, GitLab CI, Jenkins, Azure DevOps…)
-- Seule l'empreinte SHA-256 du jeton est stockée ; le jeton en clair n'est affiché qu'une fois, à la création.
CREATE TABLE jeton_api (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id  BIGINT       NOT NULL,
    nom             VARCHAR(80)  NOT NULL,
    prefixe         VARCHAR(16)  NOT NULL,
    empreinte       VARCHAR(64)  NOT NULL,
    cree_le         TIMESTAMP    NOT NULL,
    dernier_usage   TIMESTAMP,
    CONSTRAINT uk_jeton_empreinte UNIQUE (empreinte),
    CONSTRAINT fk_jeton_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateur (id) ON DELETE CASCADE
);
CREATE INDEX ix_jeton_utilisateur ON jeton_api (utilisateur_id);
