-- RevIA - schéma initial (PostgreSQL ; compatible H2 en mode PostgreSQL pour le développement)

CREATE TABLE utilisateur (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type              VARCHAR(20)  NOT NULL,
    nom               VARCHAR(80)  NOT NULL,
    email             VARCHAR(160) NOT NULL,
    mot_de_passe_hash VARCHAR(100) NOT NULL,
    cree_le           TIMESTAMP    NOT NULL,
    bloque            BOOLEAN      NOT NULL DEFAULT FALSE,
    quota_journalier  INTEGER      NOT NULL DEFAULT 50,
    CONSTRAINT uk_utilisateur_email UNIQUE (email),
    CONSTRAINT ck_utilisateur_type CHECK (type IN ('DEVELOPPEUR', 'ADMINISTRATEUR'))
);

CREATE TABLE prompt_systeme (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version  VARCHAR(20) NOT NULL,
    contenu  TEXT        NOT NULL,
    actif    BOOLEAN     NOT NULL DEFAULT FALSE,
    cree_le  TIMESTAMP   NOT NULL,
    CONSTRAINT uk_prompt_version UNIQUE (version)
);

CREATE TABLE revue (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     BIGINT       NOT NULL,
    titre              VARCHAR(160) NOT NULL,
    langage            VARCHAR(30)  NOT NULL,
    code               TEXT         NOT NULL,
    score              INTEGER      NOT NULL,
    resume             TEXT,
    mode               VARCHAR(20)  NOT NULL DEFAULT 'complet',
    cree_le            TIMESTAMP    NOT NULL,
    duree_ms           BIGINT       NOT NULL DEFAULT 0,
    fournisseur        VARCHAR(30),
    modele             VARCHAR(80),
    prompt_version     VARCHAR(20),
    nb_lignes          INTEGER      NOT NULL,
    nb_masquages       INTEGER      NOT NULL DEFAULT 0,
    problemes_rejetes  INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT fk_revue_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateur (id) ON DELETE CASCADE,
    CONSTRAINT ck_revue_score CHECK (score BETWEEN 0 AND 100)
);
CREATE INDEX ix_revue_utilisateur_date ON revue (utilisateur_id, cree_le);

CREATE TABLE probleme (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revue_id      BIGINT       NOT NULL,
    ligne         INTEGER      NOT NULL,
    categorie     VARCHAR(30)  NOT NULL,
    gravite       VARCHAR(20)  NOT NULL,
    titre         VARCHAR(200) NOT NULL,
    explication   TEXT         NOT NULL,
    owasp         VARCHAR(80),
    faux_positif  BOOLEAN      NOT NULL DEFAULT FALSE,
    corrige       BOOLEAN      NOT NULL DEFAULT FALSE,
    utile         BOOLEAN,
    ordre         INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT fk_probleme_revue FOREIGN KEY (revue_id) REFERENCES revue (id) ON DELETE CASCADE,
    CONSTRAINT ck_probleme_gravite CHECK (gravite IN ('CRITIQUE', 'MAJEURE', 'MINEURE', 'INFO')),
    CONSTRAINT ck_probleme_ligne CHECK (ligne >= 1)
);
CREATE INDEX ix_probleme_revue ON probleme (revue_id);

CREATE TABLE correction (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    probleme_id    BIGINT  NOT NULL,
    code_avant     TEXT    NOT NULL,
    code_apres     TEXT    NOT NULL,
    justification  TEXT    NOT NULL,
    copiee         BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_correction_probleme UNIQUE (probleme_id),
    CONSTRAINT fk_correction_probleme FOREIGN KEY (probleme_id) REFERENCES probleme (id) ON DELETE CASCADE
);
