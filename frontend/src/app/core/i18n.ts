/** Messages variables (quota, délai…) : motif français → gabarit anglais. */
const MOTIFS: [RegExp, string][] = [
  [/^Vous avez atteint vos (\d+) revues du jour\.$/, 'You have reached your $1 reviews for today.'],
  [/^Trop de demandes en peu de temps\. Réessayez dans (\d+) s\.$/, 'Too many requests in a short time. Try again in $1 s.'],
  [/^Les outils IA acceptent (\d+) lignes au maximum : collez une partie du code\.$/, 'AI tools accept at most $1 lines: paste part of the code.'],
];

/** Traduit un texte français dans la langue courante (inchangé en français ou s'il est inconnu). */
export function tr(fr: string | null | undefined): string {
  if (fr == null) {
    return '';
  }
  if (langueCourante() !== 'en') {
    return fr;
  }
  const direct = EN[fr] ?? EN[fr.trim()];
  if (direct !== undefined) {
    return direct;
  }
  for (const [motif, gabarit] of MOTIFS) {
    if (motif.test(fr)) {
      return fr.replace(motif, gabarit);
    }
  }
  return fr;
}

/**
 * {{ 'Nouvelle revue' | t }} — impur pour suivre le changement de langue sans recharger la page
 * (la lecture du signal de langue marque aussi le composant OnPush à revérifier).
 */
@Pipe({ name: 't', standalone: true, pure: false })
export class TPipe implements PipeTransform {
  transform(fr: string | null | undefined): string {
    return tr(fr);
  }
}
